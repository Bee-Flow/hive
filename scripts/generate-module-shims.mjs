#!/usr/bin/env node
// Single-React contract — step 2 of 3 (see src/moduleRuntime/sharedRuntime.js).
//
// Emits static ES-module shims to public/module-shims/*.js that re-export the
// host React family from window.__BEEFLOW_SHARED__. The inline import map in
// index.html maps the bare `react*` specifiers that externalized module bundles
// import to these files, so every runtime module shares the host's single React
// instance.
//
// The named exports are enumerated from the ACTUAL installed packages so the
// shims always match the React version the host bundles — a React upgrade
// regenerates them on the next build/dev (wired as prebuild + predev in
// package.json). Static, unhashed URLs mean the import map never has to change.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = resolve(HERE, '../public/module-shims');

// specifier (what a module bundle imports) → { key in the global, output file }.
// The output basenames must match the import map in index.html.
const TARGETS = [
    { specifier: 'react', key: 'react', file: 'react.js' },
    { specifier: 'react-dom', key: 'react-dom', file: 'react-dom.js' },
    { specifier: 'react-dom/client', key: 'react-dom/client', file: 'react-dom-client.js' },
    { specifier: 'react/jsx-runtime', key: 'react/jsx-runtime', file: 'react-jsx-runtime.js' },
];

const RESERVED = new Set(['default', '__esModule']);

function emitShim(mod, key) {
    // Only re-export valid JS identifiers; `default` is handled explicitly.
    const names = Object.keys(mod).filter(
        (n) => !RESERVED.has(n) && /^[A-Za-z_$][\w$]*$/.test(n),
    );
    const globalRef = `(typeof window !== 'undefined' && window.__BEEFLOW_SHARED__ && window.__BEEFLOW_SHARED__[${JSON.stringify(key)}]) || {}`;
    const lines = [
        '// AUTO-GENERATED by scripts/generate-module-shims.mjs — do not edit.',
        `// Re-exports the host '${key}' from window.__BEEFLOW_SHARED__ so runtime`,
        '// module bundles share the host React instance (single-React contract).',
        `const m = ${globalRef};`,
        "export default ('default' in m) ? m.default : m;",
    ];
    for (const n of names) {
        lines.push(`export const ${n} = m[${JSON.stringify(n)}];`);
    }
    return lines.join('\n') + '\n';
}

async function main() {
    mkdirSync(OUT_DIR, { recursive: true });
    for (const { specifier, key, file } of TARGETS) {
        const mod = await import(specifier);
        writeFileSync(resolve(OUT_DIR, file), emitShim(mod, key), 'utf8');
        console.log(`[module-shims] wrote ${file} (${Object.keys(mod).length} export(s))`);
    }
}

main().catch((err) => {
    console.error('[module-shims] generation failed:', err);
    process.exit(1);
});
